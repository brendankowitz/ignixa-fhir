using System.Text;
using Microsoft.Health.Fhir.CodeGen.FhirExtensions;
using Microsoft.Health.Fhir.CodeGen.Language;
using Microsoft.Health.Fhir.CodeGen.Models;
using Microsoft.Health.Fhir.CodeGenCommon.Packaging;

namespace Ignixa.Specification.Generators;

/// <summary>
/// Custom ILanguage implementation for generating the C# <c>IReferenceMetadataProvider</c> of a FHIR version: which
/// top-level elements of each resource are references, and to which resource types.
/// </summary>
/// <remarks>
/// Structure mode used to emit <c>*StructureDefinitionSummaryProvider.g.cs</c> files as well, which the generated core schema providers
/// replaced; the repository no longer holds or builds them, so they are no longer emitted.
/// </remarks>
public sealed class CSharpReferenceMetadataLanguage : ILanguage
{
    private const string LanguageName = "CSharpReferenceMetadata";

    /// <summary>Gets the language name.</summary>
    public string Name => LanguageName;

    /// <summary>Gets the configuration type.</summary>
    public Type ConfigType => typeof(CSharpReferenceMetadataConfig);

    /// <summary>Gets the FHIR primitive type map (not used for this generator).</summary>
    public Dictionary<string, string> FhirPrimitiveTypeMap => new();

    /// <summary>Gets a value indicating whether this language is idempotent.</summary>
    public bool IsIdempotent => true;

    /// <summary>Exports the reference metadata code.</summary>
    /// <param name="config">The configuration.</param>
    /// <param name="definitions">The definitions to export.</param>
    public void Export(object config, DefinitionCollection definitions)
    {
        if (config is not CSharpReferenceMetadataConfig metadataConfig)
        {
            throw new ArgumentException($"Configuration must be of type {nameof(CSharpReferenceMetadataConfig)}", nameof(config));
        }

        // The class prefix matches the FhirVersion enum casing (Stu3); the checked-in STU3 file is named STU3ReferenceMetadata.g.cs.
        (string classPrefix, string filePrefix) = definitions.FhirSequence switch
        {
            FhirReleases.FhirSequenceCodes.R4 => ("R4", "R4"),
            FhirReleases.FhirSequenceCodes.R4B => ("R4B", "R4B"),
            FhirReleases.FhirSequenceCodes.R5 => ("R5", "R5"),
            FhirReleases.FhirSequenceCodes.R6 => ("R6", "R6"),
            FhirReleases.FhirSequenceCodes.STU3 => ("Stu3", "STU3"),
            _ => throw new ArgumentException($"Unsupported FHIR version: {definitions.FhirSequence}")
        };

        string outputDir = Path.GetFullPath(metadataConfig.OutputDirectory);
        Directory.CreateDirectory(outputDir);

        string refMetadataPath = Path.Combine(outputDir, $"{filePrefix}ReferenceMetadata.g.cs");
        File.WriteAllText(refMetadataPath, GenerateReferenceMetadata(classPrefix, definitions, metadataConfig), Encoding.UTF8);

        Console.WriteLine($"Generated {refMetadataPath}");
    }

    private static string GenerateReferenceMetadata(string fhirVersion, DefinitionCollection definitions, CSharpReferenceMetadataConfig config)
    {
        var sb = new StringBuilder();

        // File header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// <copyright file=\"" + $"{fhirVersion}ReferenceMetadata.g.cs" + "\" company=\"Microsoft Corporation\">");
        sb.AppendLine("//     Copyright (c) Microsoft Corporation. All rights reserved.");
        sb.AppendLine("//     Licensed under the MIT License (MIT). See LICENSE in the repo root for license information.");
        sb.AppendLine("// </copyright>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Ignixa.Abstractions;");
        sb.AppendLine();
        sb.AppendLine($"namespace {config.Namespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Pre-generated reference metadata for FHIR {fhirVersion}.");
        sb.AppendLine("/// Provides efficient lookup of which elements are references and their target types.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("[CLSCompliant(false)]");
        sb.AppendLine($"public sealed class {fhirVersion}ReferenceMetadata : IReferenceMetadataProvider");
        sb.AppendLine("{");

        // Generate metadata dictionary (remains static for shared data)
        sb.AppendLine("    private static readonly Dictionary<string, List<ReferenceFieldMetadata>> _metadata = new()");
        sb.AppendLine("    {");

        // Process all resources
        var resources = definitions.ResourcesByName.OrderBy(kvp => kvp.Key).ToList();

        foreach (var (resourceName, sd) in resources)
        {
            var referenceElements = sd.cgElements(topLevelOnly: true, includeRoot: false, skipSlices: true)
                .Where(e => e.Type.Any(t => t.Code == "Reference"))
                .ToList();

            if (referenceElements.Count == 0)
                continue;

            sb.AppendLine($"        [\"{resourceName}\"] = new List<ReferenceFieldMetadata>");
            sb.AppendLine($"        {{");

            foreach (var element in referenceElements)
            {
                string elementName = element.cgName();
                int min = element.cgCardinalityMin();
                string max = element.Max ?? "*";
                bool inSummary = element.IsSummary ?? false;

                // Extract target profiles
                var referenceType = element.Type.FirstOrDefault(t => t.Code == "Reference");
                var targetProfiles = new List<string>();

                if (referenceType?.TargetProfile != null && referenceType.TargetProfile.Any())
                {
                    foreach (var targetUrl in referenceType.TargetProfile)
                    {
                        // Extract resource name from URL like "http://hl7.org/fhir/StructureDefinition/Patient"
                        string resourceType = targetUrl.Split('/').Last();
                        targetProfiles.Add(resourceType);
                    }
                }

                // Generate field metadata (positional parameters for record)
                string targetTypesArray;
                if (targetProfiles.Count > 0)
                {
                    targetTypesArray = $"new[] {{ {string.Join(", ", targetProfiles.Select(t => $"\"{t}\""))} }}";
                }
                else
                {
                    targetTypesArray = "System.Array.Empty<string>()";
                }

                sb.AppendLine($"            new ReferenceFieldMetadata(\"{elementName}\", {min}, \"{max}\", {targetTypesArray}, {(inSummary ? "true" : "false")}),");
            }

            sb.AppendLine($"        }},");
        }

        sb.AppendLine("    };");
        sb.AppendLine();

        // Instance methods implementing IReferenceMetadataProvider
        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public IReadOnlyList<ReferenceFieldMetadata> GetMetadata(string resourceType)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(resourceType);");
        sb.AppendLine("        return _metadata.TryGetValue(resourceType, out var metadata)");
        sb.AppendLine("            ? metadata");
        sb.AppendLine("            : System.Array.Empty<ReferenceFieldMetadata>();");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public bool HasReferences(string resourceType)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(resourceType);");
        sb.AppendLine("        return _metadata.ContainsKey(resourceType);");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}

/// <summary>
/// Configuration for the C# reference metadata generator.
/// </summary>
public sealed class CSharpReferenceMetadataConfig
{
    /// <summary>Gets or sets the output directory for generated files.</summary>
    public string OutputDirectory { get; set; } = string.Empty;

    /// <summary>Gets or sets the namespace for generated classes.</summary>
    public string Namespace { get; set; } = "Ignixa.Specification.Generated";
}
